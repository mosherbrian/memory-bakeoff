def _build(base: Path, rows=(_T1,), report=_REPORT, diff=_DIFF,
           receipts={}) -> tuple[Path, Path]:
    """base/team/{QUEUE.md, A.md written 09:00 PDT, D-7-timestamps/..., receipts}"""
    root = base / "team" / "D-7-timestamps"
    root.mkdir(parents=True)
    a = base / "team" / "A.md"
    a.write_text("artifact\n")
    t = datetime(2026, 9, 17, 9, 0, tzinfo=_NOW.tzinfo).timestamp()
    os.utime(a, (t, t))
    for name, when in receipts.items():
        p = base / "team" / name
        p.write_text("verify receipt\n")
        wt = when.timestamp()
        os.utime(p, (wt, wt))
    queue = base / "team" / "QUEUE.md"
    queue.write_text("| id | task | seat | cadence | artifact | cost | status |\n"
                     "|---|---|---|---|---|---|---|\n" + "\n".join(rows) + "\n")
    if report is not None:
        (root / "report.md").write_text(report)
    if diff is not None:
        (root / "fix.diff").write_text(diff)
    return root, queue


