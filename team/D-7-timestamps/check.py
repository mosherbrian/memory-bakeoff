def _when(date: str, clock: str, tz) -> datetime:
    t = datetime.fromisoformat(f"{date}T{clock}")
    if tz in TZ:
        return t.replace(tzinfo=timezone(timedelta(hours=TZ[tz])))
    if tz:
        return datetime.fromisoformat(f"{date}T{clock}{tz[:3]}:{tz[-2:]}")
    return t.astimezone()  # unlabelled: the machine's own zone


def _cells(line: str) -> list[str]:
    return [c.strip() for c in line.strip().strip("|").split("|")]


def _rows(queue_text: str):
    """(row id, artifact cell, status text) per board row. The status is every
    cell after the artifact cell, so a task that QUOTES a stamp is not a stamp."""
    for line in queue_text.splitlines():
        if not line.lstrip().startswith("|"):
            continue
        cells = _cells(line)
        if len(cells) < 5 or not re.fullmatch(r"[A-Za-z0-9][\w.-]*", cells[0]) \
                or cells[0] == "id":
            continue
        at = next((i for i, c in enumerate(cells) if "(check:" in c), 4)
        yield cells[0], cells[at], " | ".join(cells[at + 1:])


def _stamps(queue_text: str) -> dict[str, tuple[datetime, str, str]]:
    out = {}
    for rid, art, status in _rows(queue_text):
        m = STAMP.search(status)
        if m:
            try:
                out[rid] = (_when(*m.groups()), art, status)
            except ValueError:
                pass
    return out


def _expand(tok: str) -> list[str]:
    m = re.search(r"\{([^{}]*)\}", tok)
    if not m:
        return [tok]
    return [p for alt in m.group(1).split(",")
            for p in _expand(tok[:m.start()] + alt.strip() + tok[m.end():])]


def _newest_mtime(art_cell: str, project: Path):
    cell = art_cell.split("(check:")[0]
    toks = re.findall(r"`([^`]+)`", cell) or [t.rstrip(",.;:") for t in cell.split()]
    newest = None
    for tok in toks:
        if " " in tok or not re.search(r"[/.]", tok):
            continue
        for rel in _expand(tok):
            if "*" in rel and not rel.startswith(("/", "~")):
                hits = list(project.glob(rel))  # `team/EXTERNAL-*.md`: every match counts
            else:
                hits = [p for p in (Path(os.path.expanduser(rel)), project / rel,
                                    project / "team" / rel) if p.exists()][:1]
            for p in hits:
                files = [f for f in p.rglob("*") if f.is_file()] if p.is_dir() else [p]
                for f in files:
                    newest = max(newest or 0, f.stat().st_mtime)
    return newest


def _marked(status: str, *words: str) -> list[str]:
    return [b for b in BRACKET.findall(status)
            if all(w in b.lower() for w in words)]


def _check_board(queue: Path, now: datetime, tol: timedelta, baseline: dict, add) -> tuple[str, int]:
    text = queue.read_text(encoding="utf-8", errors="replace")
    stamps = _stamps(text)
    project = queue.resolve().parent.parent
    compared = excused = verified = 0
    for rid, (stamp, art, status) in stamps.items():
        if stamp > now + CLOCK_SLACK:
            add("FUTURE-STAMP", f"{rid}: stamped {stamp:%Y-%m-%d %H:%M %Z}, but this "
                f"check's clock reads {now:%Y-%m-%d %H:%M %Z}")
        mtime = _newest_mtime(art, project)
        if mtime is None:
            continue  # out of scope: no declared artifact that exists
        compared += 1
        lead = stamp - datetime.fromtimestamp(mtime, tz=timezone.utc)
        if lead > tol:
            if _marked(status, "stamp", "unreliable"):
                excused += 1
            else:
                receipt = queue.parent / f"CORVID-{rid}-VERIFY.md"
                if receipt.is_file():
                    back = stamp - datetime.fromtimestamp(
                        receipt.stat().st_mtime, tz=timezone.utc)
                    if timedelta(0) <= back <= tol:
                        verified += 1
                        continue
                    if back < timedelta(0):
                        add("RECEIPT-AFTER-STAMP", f"{rid}: the verify receipt is "
                            f"{-back.total_seconds() / 60:.0f} min NEWER than the "
                            f"stamp - a receipt written after the claimed close is "
                            f"itself a stamp problem")
                        continue
                add("STAMP-LEADS-ARTIFACT", f"{rid}: stamp leads the artifact's newest "
                    f"mtime by {lead.total_seconds() / 60:.0f} min (tolerance "
                    f"{tol.total_seconds() / 60:.0f}); correct it visibly or mark it "
                    "`[stamp unreliable: ...]`")
    changed = 0
    for rid, was in baseline.items():
        if rid not in stamps:
            continue  # row left the board, or lost its stamp format: not a rewrite
        old = datetime.fromisoformat(was)
        if stamps[rid][0] != old:
            changed += 1
            notes = _marked(stamps[rid][2], "stamp", "corrected")
            if not any(f"{old.astimezone(stamps[rid][0].tzinfo):%H:%M}" in n for n in notes):
                add("SILENT-REWRITE", f"{rid}: stamp was {old:%Y-%m-%d %H:%M %Z}, is now "
                    f"{stamps[rid][0]:%Y-%m-%d %H:%M %Z}, and the row carries no "
                    f"`[corrected - stamp: first written {old:%H:%M} ...]` note")
    return (f"{len(stamps)} stamped rows, {compared} compared against an existing "
            f"artifact, {excused} marked unreliable, {verified} verify-closed by "
            f"receipt, {changed} changed since baseline"), changed


def _line(text: str, label: str):
    m = re.search(r"(?im)^[\s>*#-]*\**" + label + r"\**\s*:\**\s*(.+)$", text)
    v = m.group(1).strip().strip("*`").strip() if m else None
    return v if v and not PLACEHOLDER.match(v) else None


def _check_report(root: Path, changed: int, add) -> None:
    missing = [f for f in FILES
               if not (root / f).is_file() or not (root / f).stat().st_size]
    for f in missing:
        add("MISSING-FILE", f"{f} (absent or empty)")
    if missing:
        return
    report = (root / "report.md").read_text(encoding="utf-8", errors="replace")
    diff = (root / "fix.diff").read_text(encoding="utf-8", errors="replace")

    touched = {Path(p).name for p in re.findall(r"(?m)^\+\+\+ (?:b/)?(\S+)", diff)
               if p != "/dev/null"}
    if not touched or not re.search(r"(?m)^[+-](?![+-]{2} )\s*\S", diff):
        add("DIFF-EMPTY", "fix.diff names no changed file, or changes no line")
    mech = _line(report, r"mechanism(?: changed)?")
    if mech is None or not any(name in mech for name in touched):
        add("MECHANISM-UNNAMED", "report.md needs `Mechanism changed: ...` naming a file "
            f"fix.diff really changes {sorted(touched)}; got {mech!r}")

    cause = _line(report, r"(?:root )?cause")
    if cause is None or len(cause.split()) < 5:
        add("CAUSE-UNSTATED", "report.md needs `Cause: <why a seat writes a time that is "
            f"not the clock>`; got {cause!r}")
    else:
        m = re.search(r"time\s?zone|\bTZ\b|utc offset", cause, re.I)
        if m and not re.search(r"\b(?:not|no|never|neither)\b|n't", cause[:m.start()], re.I):
            add("CAUSE-IS-TIMEZONE", "the row rules a timezone out (the error is not "
                f"constant); got {cause!r}")

    decisions = re.findall(r"(?im)^[\s>*#-]*\**existing stamps\**\s*:\**\s*`?([a-z-]+)", report)
    if len(decisions) != 1 or decisions[0].lower() not in ("corrected", "marked-unreliable"):
        add("STAMP-DECISION-UNSTATED", "report.md needs exactly one line `Existing stamps: "
            f"corrected` or `Existing stamps: marked-unreliable`; found {decisions}")
    elif decisions[0].lower() == "marked-unreliable" and changed:
        add("DECISION-CONTRADICTS-BOARD", f"report says stamps were only marked, but "
            f"{changed} stamp(s) differ from the baseline")


def check(root: Path, queue: Path, now: datetime, tol_min: float, baseline: dict):
    findings: list[tuple[str, str]] = []
    add = lambda marker, msg: findings.append((marker, msg))
    summary, changed = "", 0
    if not queue.is_file():
        add("MISSING-FILE", f"board {queue} not found")
    else:
        summary, changed = _check_board(queue, now, timedelta(minutes=tol_min), baseline, add)
    _check_report(root, changed, add)
    return findings, summary


# ---- selftest: the gate must be able to fail, and able to pass ----

_NOW = datetime(2026, 9, 17, 12, 0, tzinfo=timezone(timedelta(hours=-7)))
