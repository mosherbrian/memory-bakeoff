#!/usr/bin/env python3
"""Gate for QUEUE row D-7 (the board's own timestamps are not evidence).

plumb-fable, row D-7G, 2026-09-17. Written FROM ROW D-7's TEXT ALONE, before any
D-7 artifact existed (`team/D-7-timestamps/` was absent). This gate is an
INSTRUMENT, not a receipt: it does not trust report.md's account of the stamps,
it re-derives the comparison from the board and the filesystem on every run.

Extended corvid-dsh, row D-12 (2026-09-17): verify-receipt excusal. The four
S7-*G verify closes tripped this gate at 15:42 with true, clock-read stamps —
a reviewer closing a row later is ELAPSED TIME, not skew. Declared in the row
before implementation: a receipt `team/CORVID-<ROW>-VERIFY.md` whose mtime is
within tolerance BELOW the stamp excuses the lead; a receipt NEWER than the
stamp is its own finding; a stale receipt (older than tolerance below the
stamp) leaves the lead flagged. Authored by corvid, verified by kiln — the
gate is not refitted by the party it excuses.

Part 1 - the comparison, recomputed (marker in brackets)
  For every QUEUE.md row whose status carries a stamp
        done: [seat] YYYY-MM-DD HH:MM[:SS] [PDT|PST|UTC|Z|+hh:mm]
  AND whose declared artifact exists, take the artifact's newest mtime and:
    [FUTURE-STAMP]          the stamp is later than this check's own clock.
                            Never excused.
    [STAMP-LEADS-ARTIFACT]  the stamp is more than TOLERANCE (10 min, stated
                            in the output) ahead of the newest mtime. Work
                            cannot finish before its files do. Excused only
                            when the row carries a visible bracketed mark,
                            e.g. `[stamp unreliable: ...]`, or when a verify
                            receipt `team/CORVID-<ROW>-VERIFY.md` exists with
                            its mtime within TOLERANCE BELOW the stamp.
    [RECEIPT-AFTER-STAMP]   a verify receipt exists but is NEWER than the
                            stamp: a receipt written after the claimed close
                            is itself a stamp problem. Not excused.
    [SILENT-REWRITE]        a stamp differs from BASELINE - the board as it
                            stood when this gate was written, before D-7
                            touched anything - and the row does not carry
                            `[corrected - stamp: first written HH:MM ...]`
                            quoting the ORIGINAL time. History may be
                            corrected; it may not be corrected invisibly.
Part 2 - the report
    [MISSING-FILE]             report.md, fix.diff
    [DIFF-EMPTY]               fix.diff changes nothing
    [MECHANISM-UNNAMED]        report.md needs a line `Mechanism changed: ...`
                               naming a file that fix.diff REALLY changes
    [CAUSE-UNSTATED]           report.md needs a line `Cause: ...` (row part a)
    [CAUSE-IS-TIMEZONE]        the row rules a timezone out: the error is not
                               constant
    [STAMP-DECISION-UNSTATED]  report.md needs exactly one line
                               `Existing stamps: corrected` or
                               `Existing stamps: marked-unreliable`
    [DECISION-CONTRADICTS-BOARD]  says marked-unreliable, but stamps changed

Limit, stated on purpose: mtime is the newest write, so a later edit to an
artifact hides an earlier lead; and BASELINE only knows the stamps that existed
on 2026-09-17. Whether the stated cause is the TRUE cause stays with the named
verifier.

Exit contract (team/tools/check_checker_exit_contracts.py): 0 clean, 1 with a
named marker and the line `D-7 gate findings: N`, never a traceback.

Usage:
  python3 check.py [ROOT] [--queue QUEUE.md] [--tolerance-min N] [--now ISO]
  python3 check.py --selftest  # a future stamp REJECTED, a clean board ACCEPTED
"""
